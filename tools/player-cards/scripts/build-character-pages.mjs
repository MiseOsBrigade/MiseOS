#!/usr/bin/env node
// Regenerates docs/characters/*.md, docs/cards/*.md, docs/characters/README.md and the README
// card/character links from data/characters/*.json and data/player-cards.json.
// Data is produced by tools/player-cards/scripts/align-characters.py; this script never adds facts.
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../../..');
process.chdir(ROOT);
const UNDEF = 'Not yet defined in the source material';
const GH = 'https://github.com/MiseOsBrigade/MiseOS/blob/miseos-universe/';
const COLL = {
  'long-cards': 'Long Cards', '1by1-chefs': '1×1 Chefs', 'cartoon-chefs': 'Cartoon Chefs',
  'character-building': 'Character Building Theme', 'orchestra-trading-cards': 'Mise Orchestra Trading Cards (Season 1)',
  'final-roster': 'Final Roster', 'registry-pages': 'Registry Catalogue Pages', 'icloud-screens': 'Studio Art & Screens',
};
const KIND = { registry_character: 'Registry character agent', registry_manifest: 'Registry manifest (product / tool)', card_character: 'Card-defined chef (catalogue: visual reference only)' };
const STATUS = {
  implemented_in_code: 'Implemented in code', referenced_in_app_code: 'Referenced in app code (no dedicated handler)',
  described_in_docs_only: 'Described in docs only', not_defined: UNDEF,
};

const cardsDoc = JSON.parse(fs.readFileSync('data/player-cards.json', 'utf8'));
const ents = fs.readdirSync('data/characters').filter((f) => f.endsWith('.json')).sort()
  .map((f) => JSON.parse(fs.readFileSync(path.join('data/characters', f), 'utf8')));
const bySlug = Object.fromEntries(ents.map((e) => [e.slug, e]));

const rel = (from, to) => path.relative(path.dirname(from), to).split(path.sep).join('/');
const v = (x) => (x === undefined || x === null || x === '' || (Array.isArray(x) && !x.length) ? UNDEF : x);
const src = (e, k) => (e.sources?.[k] ? ` <sub>source: \`${e.sources[k]}\`</sub>` : '');
const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const link = (from, p, line) => `[\`${p}${line ? `:${line}` : ''}\`](${rel(from, p)}${line ? `#L${line}` : ''})`;
export const cardPage = (c) => c.page;

function cardGallery(out, cards) {
  if (!cards.length) return `_${UNDEF} (no player card art is linked to this entry yet)._\n`;
  return cards.map((c) => `<a href="${rel(out, c.file)}"><img src="${rel(out, c.thumbnail)}" alt="${esc(c.title ?? path.basename(c.file))}" width="160" /></a>`).join('\n')
    + '\n\n| Card | Collection | Printed title | Match method | Full size |\n|---|---|---|---|---|\n'
    + cards.map((c) => `| \`${path.basename(c.file)}\` | ${COLL[c.collection] ?? c.collection} | ${esc(c.title ?? '—')} | ${c.match_method ?? '—'} | [open](${rel(out, c.file)}) |`).join('\n') + '\n';
}

function charPage(e) {
  const out = `docs/characters/${e.slug}.md`;
  const L = [];
  const row = (k, val, sk) => L.push(`| ${k} | ${esc(typeof val === 'object' ? JSON.stringify(val) : v(val))}${src(e, sk ?? k.toLowerCase())} |`);
  L.push(`<!-- generated by tools/player-cards/scripts/build-character-pages.mjs from data/characters/${e.slug}.json; do not edit by hand -->`);
  L.push(`# ${e.name}`, '');
  if (e.cards[0]) L.push(`<a href="${rel(out, e.cards[0].file)}"><img src="${rel(out, e.cards[0].thumbnail)}" alt="${esc(e.name)}" width="240" align="right" /></a>`, '');
  L.push(`**${KIND[e.kind]}** · Implementation: **${STATUS[e.implementation.status]}** · Detail record: [\`data/characters/${e.slug}.json\`](../../data/characters/${e.slug}.json)`, '');
  L.push('Every field below comes from a repository source (shown as `source:`). Where no source exists the page says _' + UNDEF + '_.', '');
  L.push('## Identity', '', '| Field | Value |', '|---|---|');
  row('Name', e.name, 'name');
  row('Aliases / printed variants', e.aliases.length ? e.aliases.join(', ') : UNDEF, 'aliases');
  row('Role / title', e.role, 'role');
  row('Kitchen / department', e.department, 'department');
  row('Department mission', e.department_mission, 'department_mission');
  row('Registry rarity', e.rarity, 'rarity');
  if (e.level) row('Level', e.level, 'level');
  for (const [k, val] of Object.entries(e.ids ?? {})) row(`ID: ${k}`, val, `ids.${k}`);
  row('Collections', e.collections.length ? e.collections.map((c) => COLL[c] ?? c).join(', ') : UNDEF, 'cards');
  row('Cards linked', e.cards.length, 'cards');
  if (e.catalogue_status) row('Catalogue status', e.catalogue_status, 'catalogue_status');
  if (e.role_category) row('Role category', e.role_category, 'role_category');
  L.push('', '## Player cards', '', cardGallery(out, e.cards));
  L.push('## Card metadata (as printed)', '', '| Field | Value |', '|---|---|');
  row('Printed rarity', e.card_rarity_printed, 'card_rarity_printed');
  row('Printed stars', e.card_stars_printed, 'card_stars_printed');
  row('Printed meters', Array.isArray(e.card_meters_printed) ? e.card_meters_printed.join(', ') : e.card_meters_printed, 'card_meters_printed');
  row('Roster stats', e.stats && typeof e.stats === 'object' ? Object.entries(e.stats).map(([k, x]) => `${k} ${x}`).join(' · ') : e.stats, 'stats');
  row('Abilities', e.abilities?.length ? e.abilities.join(', ') : UNDEF, 'abilities');
  if (e.orchestra_card) row('Mise Orchestra card', Object.entries(e.orchestra_card).map(([k, x]) => `${k}: ${x}`).join(' · '), 'orchestra_card');
  row('Lore', e.lore, 'lore');
  row('Signature phrase', e.signature_phrase, 'signature_phrase');
  if (e.unique_trait) row('Unique trait', e.unique_trait, 'unique_trait');
  if (e.card_text.length) {
    L.push('', '<details><summary>Full printed card text (OCR)</summary>', '');
    for (const t of e.card_text) L.push(`**\`${path.basename(t.file)}\`**: ${esc(t.printed_text.join(' · '))}`, '');
    L.push('</details>');
  }
  L.push('', '## Workflow', '', '| Step | Value |', '|---|---|');
  row('Summary', e.workflow.summary, 'workflow.summary');
  row('Inputs', Array.isArray(e.workflow.inputs) ? e.workflow.inputs.join(', ') : e.workflow.inputs, 'workflow.inputs');
  row('Outputs', Array.isArray(e.workflow.outputs) ? e.workflow.outputs.join(', ') : e.workflow.outputs, 'workflow.outputs');
  row('Proof gate', e.workflow.proof_gate, 'workflow.proof_gate');
  L.push('', '## Actions / commands', '');
  if (Array.isArray(e.actions)) for (const a of e.actions) {
    const { source, ...rest } = a;
    L.push(`- ${Object.entries(rest).map(([k, x]) => `${k}: \`${x}\``).join(' · ')} <sub>source: \`${source}\`</sub>`);
  } else L.push(`_${UNDEF}_`);
  L.push('', '## Implementation', '');
  const im = e.implementation;
  L.push(`**Status:** ${STATUS[im.status]}`, '');
  if (im.handler) L.push(`- Capability handler \`${im.handler.name}\`: ${link(out, im.handler.path, im.handler.line)} (implemented in code)`);
  if (im.tool_dir) L.push(`- Tool directory: [\`${im.tool_dir}\`](${rel(out, im.tool_dir)}) (implemented in code)`);
  if (e.runtime) L.push(`- Runtime: engine \`${e.runtime.engine}\` ≥ ${e.runtime.minimum_version}, handler \`${e.runtime.handler}\`${src(e, 'runtime')}`);
  if (e.permissions) L.push(`- Permissions: ${Object.entries(e.permissions).map(([k, x]) => `${k}=\`${x}\``).join(', ')}${src(e, 'permissions')}`);
  if (e.distribution) L.push(`- Distribution channels: ${e.distribution.channels.join(', ')}${src(e, 'distribution')}`);
  if (e.marketplace) L.push(`- Marketplace: category \`${e.marketplace.category}\`, published \`${e.marketplace.published}\`${src(e, 'marketplace')}`);
  if (im.app_code_refs?.length) { L.push('', 'Application code that uses this entry:'); for (const r of im.app_code_refs) L.push(`- ${link(out, r.path, r.line)}`); }
  const other = (im.code_refs ?? []).filter((r) => !(im.app_code_refs ?? []).some((a) => a.path === r.path));
  if (other.length) { L.push('', 'Roster data / types / tests in code that list this entry (not an implementation):'); for (const r of other) L.push(`- ${link(out, r.path, r.line)}`); }
  if (im.data_refs?.length) { L.push('', 'Data files that reference it:'); for (const r of im.data_refs) L.push(`- ${link(out, r.path, r.line)}`); }
  if (im.doc_refs?.length || e.profile_doc) {
    L.push('', 'Docs that describe it (docs only, not code):');
    if (e.profile_doc) L.push(`- ${link(out, e.profile_doc)}`);
    for (const r of im.doc_refs ?? []) L.push(`- ${link(out, r.path, r.line)}`);
  }
  if (im.status === 'not_defined') L.push(`_${UNDEF}: no code, workflow or docs reference this entry beyond its card art._`);
  L.push('', `<sub>${im.note}</sub>`);
  L.push('', '## Where and how it helps', '', '| Aspect | Value |', '|---|---|');
  row('Station / stage', e.helps.station, 'helps.station');
  row('Mission', e.helps.mission, 'department_mission');
  row('Problem it addresses', e.helps.problem, 'workflow.summary');
  row('Safety gate', e.helps.proof_gate, 'workflow.proof_gate');
  L.push('', '## Related characters', '');
  if (Array.isArray(e.related)) L.push(e.related.map((r) => (r.slug && bySlug[r.slug] ? `[${r.name}](./${r.slug}.md)` : r.name)).join(' · ') + src(e, 'related'));
  else L.push(`_${UNDEF}_`);
  if (e.canon_bible) {
    L.push('', '## Canon Bible', '', `Mentioned in [\`${e.canon_bible.path}\`](../../${e.canon_bible.path}):`, '');
    for (const m of e.canon_bible.mentions) L.push(`- line ${m.line}: \`${m.text}\``);
  }
  L.push('', '## Sources', '', '| Field | Source |', '|---|---|');
  for (const [k, s] of Object.entries(e.sources)) L.push(`| ${k} | \`${esc(s.trim())}\` |`);
  L.push('', '[← All characters](./README.md)', '');
  return [out, L.join('\n')];
}

function unmatchedCardPage(c, ocr) {
  const out = c.page; const L = [];
  L.push('<!-- generated by tools/player-cards/scripts/build-character-pages.mjs; do not edit by hand -->');
  L.push(`# Card: ${c.title ?? path.basename(c.file)}`, '');
  L.push(`<a href="${rel(out, c.file)}"><img src="${rel(out, c.file)}" alt="${esc(c.title ?? '')}" width="480" /></a>`, '');
  L.push(`This card is not yet matched to a registry character, registry manifest or catalogue chef. Fields below are read from [\`data/player-cards.json\`](../../data/player-cards.json) and OCR in [\`data/player-cards-ocr.json\`](../../data/player-cards-ocr.json).`, '');
  L.push('| Field | Value |', '|---|---|');
  L.push(`| Collection | ${COLL[c.collection] ?? c.collection} |`, `| Printed title | ${esc(c.title ?? UNDEF)} |`, `| File | [\`${c.file}\`](${rel(out, c.file)}) |`,
    `| Original size | ${c.original_size ? c.original_size.join('×') : UNDEF} |`, `| Original source | \`${esc(c.source ?? UNDEF)}\` |`,
    `| Duplicates | ${c.duplicates?.length ? c.duplicates.map((d) => `\`${esc(d)}\``).join('<br>') : '—'} |`,
    `| Character | ${UNDEF} |`, `| Workflow / actions / implementation | ${UNDEF} |`);
  L.push('', '## Printed text (OCR)', '', ocr?.length ? ocr.map((x) => `- ${esc(x)}`).join('\n') : '_No text detected on this card._', '', '[← All characters](../characters/README.md)', '');
  return [out, L.join('\n')];
}

const ocrAll = JSON.parse(fs.readFileSync('data/player-cards-ocr.json', 'utf8'));
const pages = [];
for (const e of ents) pages.push(charPage(e));
for (const c of cardsDoc.cards) if (!c.entity_slug) pages.push(unmatchedCardPage(c, ocrAll[c.file]));

// index
const idx = ['<!-- generated by tools/player-cards/scripts/build-character-pages.mjs; do not edit by hand -->', '# MiseOS characters', '',
  `${ents.length} entries: ${ents.filter((e) => e.kind === 'registry_character').length} registry character agents, ${ents.filter((e) => e.kind === 'registry_manifest').length} registry manifests and ${ents.filter((e) => e.kind === 'card_character').length} card-defined chefs. ${cardsDoc.cards.filter((c) => c.entity_slug).length} of ${cardsDoc.cards.length} player cards are matched; the rest have their own [card pages](../cards/).`, '',
  '| Character | Kind | Role | Collection(s) | Implemented | Status | Cards |', '|---|---|---|---|---|---|---|'];
for (const e of ents) idx.push(`| [${esc(e.name)}](./${e.slug}.md) | ${e.kind.replace('_', ' ')} | ${esc(e.role)} | ${e.collections.map((c) => COLL[c] ?? c).join(', ') || '—'} | ${e.implementation.status === 'implemented_in_code' ? 'yes' : 'no'} | ${STATUS[e.implementation.status]} | ${e.cards.length} |`);
const um = cardsDoc.cards.filter((c) => !c.entity_slug);
idx.push('', `## Unmatched cards (${um.length})`, '', um.map((c) => `[${esc(c.title ?? path.basename(c.file))}](../cards/${path.basename(c.page)})`).join(' · '), '');
pages.push(['docs/characters/README.md', idx.join('\n')]);

const check = process.argv.includes('--check');
let stale = 0;
for (const dir of ['docs/characters', 'docs/cards']) {
  fs.mkdirSync(dir, { recursive: true });
  if (!check) for (const f of fs.readdirSync(dir)) if (f.endsWith('.md')) fs.rmSync(path.join(dir, f));
}
for (const [p, body] of pages) {
  if (check) { if (!fs.existsSync(p) || fs.readFileSync(p, 'utf8') !== body) { stale++; console.error(`stale: ${p}`); } }
  else fs.writeFileSync(p, body);
}

// README links
let readme = fs.readFileSync('README.md', 'utf8');
const pageOf = Object.fromEntries(cardsDoc.cards.map((c) => [c.file, c.page]));
const start = readme.indexOf('## Player cards'); const end = readme.indexOf('\n## ', start + 5);
let sec = readme.slice(start, end);
sec = sec.replace(/<a href="\.\/([^"]+)"><img src="\.\/(assets\/player-cards\/[^"]+)"/g, (m, href, thumb) => {
  const card = cardsDoc.cards.find((c) => c.thumbnail === thumb);
  return card ? `<a href="./${card.page}"><img src="./${thumb}"` : m;
});
sec = sec.replace(/^300 unique player cards.*$/m, `${cardsDoc.cards.length} unique player cards across 8 collections. Each thumbnail opens its character page (workflow, actions, implementation, card metadata and sources) or, for unmatched cards, a per-card page; see the [character index](./docs/characters/README.md). ${cardsDoc.cards.filter((c) => c.entity_slug).length} cards are matched to ${new Set(cardsDoc.cards.filter((c) => c.entity_slug).map((c) => c.entity_slug)).size} characters / registry entries.`);
sec = sec.replace(/(<summary><b>[^<]+<\/b> — (\d+) cards \()\d+( matched to characters\)<\/summary>)([\s\S]*?)(?=<summary>|$)/g, (m, a, _n, b, body) => {
  const k = (body.match(/href="\.\/docs\/characters\//g) || []).length; return `${a}${k}${b}${body}`;
});
readme = readme.slice(0, start) + sec + readme.slice(end);
readme = readme.replace(/<a href="\.\/characters\/([a-z0-9-]+)\/README\.md"><img src="\.\/assets\/characters\//g, (m, s) => (bySlug[s] ? `<a href="./docs/characters/${s}.md"><img src="./assets/characters/` : m));
if (check) { if (fs.readFileSync('README.md', 'utf8') !== readme) { stale++; console.error('stale: README.md'); } }
else fs.writeFileSync('README.md', readme);
if (check && stale) { console.error(`${stale} generated files are stale; run npm run cards:pages`); process.exit(1); }
console.log(`${check ? 'Checked' : 'Wrote'} ${pages.length} pages (${ents.length} characters, ${um.length} unmatched cards).`);
