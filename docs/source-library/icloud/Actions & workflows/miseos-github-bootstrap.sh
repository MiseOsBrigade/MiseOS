#!/usr/bin/env bash
set -euo pipefail

VERSION="0.1.0"
PAYLOAD_SHA256="d78406f211de5cff286e72091822d7c6c50546c009343bea1ec52d813a17913a"
TARGET="."
FORCE=0
DO_COMMIT=0
DO_PUSH=0

usage() {
  cat <<'EOF'
MiseOS DevOps Foundry bootstrap

Usage:
  bash miseos-github-bootstrap.sh [options]

Options:
  --target PATH   Install into PATH (default: current directory)
  --force         Overwrite files that already exist
  --commit        git add + commit after validation
  --push          push the current branch to origin (implies --commit)
  -h, --help      Show help

Safe default: the installer aborts before copying if any destination file exists.
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --target) TARGET="${2:?missing value for --target}"; shift 2 ;;
    --force) FORCE=1; shift ;;
    --commit) DO_COMMIT=1; shift ;;
    --push) DO_PUSH=1; DO_COMMIT=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "Unknown option: $1" >&2; usage >&2; exit 2 ;;
  esac
done

mkdir -p "$TARGET"
TARGET="$(cd "$TARGET" && pwd)"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
ARCHIVE="$TMP/miseos-devops-foundry.tar.gz"

# Decode the embedded archive with the available base64 implementation.
if base64 --help 2>&1 | grep -q -- '--decode'; then
  sed -n '/^__MISEOS_PAYLOAD_BELOW__$/,$p' "$0" | tail -n +2 | base64 --decode > "$ARCHIVE"
elif base64 -D </dev/null >/dev/null 2>&1; then
  sed -n '/^__MISEOS_PAYLOAD_BELOW__$/,$p' "$0" | tail -n +2 | base64 -D > "$ARCHIVE"
else
  echo "No compatible base64 decoder found." >&2
  exit 1
fi

if command -v sha256sum >/dev/null 2>&1; then
  ACTUAL_SHA="$(sha256sum "$ARCHIVE" | awk '{print $1}')"
elif command -v shasum >/dev/null 2>&1; then
  ACTUAL_SHA="$(shasum -a 256 "$ARCHIVE" | awk '{print $1}')"
else
  echo "Need sha256sum or shasum for payload verification." >&2
  exit 1
fi

if [[ "$ACTUAL_SHA" != "$PAYLOAD_SHA256" ]]; then
  echo "Payload checksum mismatch." >&2
  echo "expected: $PAYLOAD_SHA256" >&2
  echo "actual:   $ACTUAL_SHA" >&2
  exit 1
fi

tar -xzf "$ARCHIVE" -C "$TMP"
SRC="$TMP/miseos-devops-foundry"
[[ -d "$SRC" ]] || { echo "Embedded archive is missing the expected root directory." >&2; exit 1; }

if [[ "$FORCE" -ne 1 ]]; then
  conflicts=()
  while IFS= read -r -d '' f; do
    rel="${f#"$SRC"/}"
    [[ -e "$TARGET/$rel" ]] && conflicts+=("$rel")
  done < <(find "$SRC" -type f -print0)

  if (( ${#conflicts[@]} > 0 )); then
    echo "Install stopped: ${#conflicts[@]} destination file(s) already exist." >&2
    printf '  %s\n' "${conflicts[@]:0:20}" >&2
    (( ${#conflicts[@]} > 20 )) && echo "  ..." >&2
    echo "Re-run with --force only after reviewing the conflicts." >&2
    exit 3
  fi
fi

cp -a "$SRC/." "$TARGET/"

echo "Installed MiseOS DevOps Foundry v$VERSION into: $TARGET"

if command -v python3 >/dev/null 2>&1 && [[ -f "$TARGET/scripts/validate_bundle.py" ]]; then
  (cd "$TARGET" && python3 scripts/validate_bundle.py)
else
  echo "Note: python3 unavailable; skipped bundle validator."
fi

if [[ -f "$TARGET/scripts/validate_polyrepo_manifest.py" && -f "$TARGET/templates/polyrepo/release.yaml" ]] && command -v python3 >/dev/null 2>&1; then
  (cd "$TARGET" && python3 scripts/validate_polyrepo_manifest.py templates/polyrepo/release.yaml)
fi

if [[ "$DO_COMMIT" -eq 1 ]]; then
  command -v git >/dev/null 2>&1 || { echo "git is required for --commit." >&2; exit 1; }
  git -C "$TARGET" rev-parse --is-inside-work-tree >/dev/null 2>&1 || {
    echo "--commit requires TARGET to be inside a git repository." >&2
    exit 1
  }
  git -C "$TARGET" add -A
  if git -C "$TARGET" diff --cached --quiet; then
    echo "No staged changes to commit."
  else
    git -C "$TARGET" commit -m "chore: install MiseOS DevOps Foundry v$VERSION"
  fi
fi

if [[ "$DO_PUSH" -eq 1 ]]; then
  git -C "$TARGET" remote get-url origin >/dev/null 2>&1 || {
    echo "--push requires an 'origin' remote." >&2
    exit 1
  }
  BRANCH="$(git -C "$TARGET" branch --show-current)"
  [[ -n "$BRANCH" ]] || { echo "Cannot push from detached HEAD." >&2; exit 1; }
  git -C "$TARGET" push -u origin "$BRANCH"
fi

cat <<'EOF'

Next recommended checks:
  git status
  make validate 2>/dev/null || true

To inspect before enabling templates:
  templates/workflows/
  templates/agentic/
  templates/polyrepo/
  actions/
EOF

exit 0
