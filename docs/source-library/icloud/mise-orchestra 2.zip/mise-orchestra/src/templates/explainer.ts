import type { MiseConfig } from "../schema/mise-schema.js";

/**
 * Renders docs/mise-orchestra.md — a human-readable orientation guide
 * that lives alongside the code. Written in plain Markdown so it renders
 * on GitHub without any tooling.
 */
export function renderExplainer(config: MiseConfig): string {
  const activeModules = Object.entries(config.modules)
    .filter(([, enabled]) => enabled)
    .map(([name]) => name);

  const moduleDescriptions: Record<string, string> = {
    pr: "**PR Chef (Sommelier)** — reviews pull requests against the policies in `mise.yaml`",
    brigade: "**Brigade (Brigadier)** — coordinates multi-repo change sets and cross-cutting concerns",
    salt_shakers: "**Salt Shakers** — lightweight dev-environment scaffolding and dependency nudges",
    locker: "**Locker (Git Locker)** — enforces branch protection rules and sign-commit policies",
    gpu: "**GPU Pack** — compute-intensive analysis jobs (CI cost, bundle size, performance profiling)",
  };

  const moduleLines = activeModules
    .map((m) => `- ${moduleDescriptions[m] ?? m}`)
    .join("\n");

  return `# Mise DevOps Orchestra

> Everything in its place, before it hits production.

This repository uses [Mise DevOps Orchestra](https://github.com/GoodshytGroup/mise-orchestra)
to keep development practices consistent across the team. This document explains
what that means for day-to-day work.

---

## What Mise does

Mise reads \`mise.yaml\` at the repo root and runs a set of lightweight checks
on pull requests and pushes. Right now it is running in **${config.mode} mode**,
which means:

${config.mode === "advisory"
    ? `- ✅ Mise **can** post review comments and check annotations on PRs
- ✅ Mise **can** surface policy warnings in the Actions tab
- ⛔ Mise **cannot** block a merge or fail a required check`
    : `- ✅ Mise **can** post review comments and check annotations on PRs
- ✅ Mise **can** surface policy warnings in the Actions tab
- ⛔ Mise **will** fail the check and block merge when a policy is violated`}

Switching modes is a one-line edit in \`mise.yaml\`:

\`\`\`yaml
mise:
  mode: advisory   # change to "enforced" when your team is ready
\`\`\`

---

## Active modules

${moduleLines || "_No modules currently enabled._"}

---

## Policy quick-reference

| Policy | Threshold |
|--------|-----------|
| Max changed files per PR | ${config.policies.pr.max_changed_files} |
| Max lines changed per PR | ${config.policies.pr.max_lines_changed} |
| Stale-branch age | ${config.policies.stewardship.stale_branch_days} days |
| Auto-cleanup stale branches | ${config.policies.stewardship.auto_cleanup ? "enabled" : "disabled (manual only)"} |
| Required reviewers | ${config.policies.stewardship.require_reviewers} |
| Require signed commits | ${config.policies.security.require_signed_commits ? "yes" : "not required"} |
| Block force-push to default | ${config.policies.security.block_force_push_to_default ? "yes" : "no"} |

Full policy definitions live in \`mise.yaml\`. All values are editable — Mise
re-reads the file on every workflow run.

---

## How to update

Edit \`mise.yaml\` directly. Changes take effect on the next PR or push.
There is no deploy step and no secret to rotate.

If you need to add or remove modules, set their value to \`true\` or \`false\`
in the \`modules:\` block of \`mise.yaml\`.

---

## Repository profile

This repo is classified as **${config.repo_profile}**. That classification drove
the initial policy defaults above. If the defaults don't fit, edit \`mise.yaml\`
— the profile field is a comment, not a constraint.

---

_Generated by \`mise-orchestra init\`. Last regenerated: ${new Date().toISOString().split("T")[0]}._
`;
}
