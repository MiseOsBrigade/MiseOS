import {
  MiseConfigSchema,
  type MiseConfig,
  type MiseEnvironment,
  type Policies,
  type RepoProfile,
} from "../schema/mise-schema.js";

/**
 * Profile-tailored policy defaults. These are starting points, not
 * verdicts — mode is always "advisory" coming out of init, so a wrong
 * guess here only ever shows up as a comment on a PR, never a blocked
 * merge.
 */
function defaultPoliciesForProfile(profile: RepoProfile): Policies {
  switch (profile) {
    case "service":
      return {
        pr: {
          enabled: true,
          max_changed_files: 50,
          max_lines_changed: 800,
          require_tests_when_paths_match: ["src/**", "services/**"],
          risky_paths: ["infra/**", "auth/**", ".github/workflows/**"],
        },
        stewardship: { enabled: true, stale_branch_days: 30, auto_cleanup: false, require_reviewers: 1 },
        security: { enabled: true, require_signed_commits: false, block_force_push_to_default: true },
      };
    case "library":
      return {
        pr: {
          enabled: true,
          max_changed_files: 40,
          max_lines_changed: 600,
          require_tests_when_paths_match: ["src/**"],
          risky_paths: ["src/index.*", "package.json", ".github/workflows/**"],
        },
        stewardship: { enabled: true, stale_branch_days: 21, auto_cleanup: false, require_reviewers: 1 },
        security: { enabled: true, require_signed_commits: false, block_force_push_to_default: true },
      };
    case "infra":
      return {
        pr: {
          enabled: true,
          max_changed_files: 30,
          max_lines_changed: 500,
          require_tests_when_paths_match: [],
          risky_paths: ["**/*.tf", "**/*.tfvars", "modules/**", ".github/workflows/**"],
        },
        stewardship: { enabled: true, stale_branch_days: 14, auto_cleanup: false, require_reviewers: 1 },
        security: { enabled: true, require_signed_commits: false, block_force_push_to_default: true },
      };
    case "data":
      return {
        pr: {
          enabled: true,
          max_changed_files: 60,
          max_lines_changed: 1000,
          require_tests_when_paths_match: ["pipelines/**", "dags/**"],
          risky_paths: ["data/schemas/**", "pipelines/**"],
        },
        stewardship: { enabled: true, stale_branch_days: 30, auto_cleanup: false, require_reviewers: 1 },
        security: { enabled: true, require_signed_commits: false, block_force_push_to_default: true },
      };
    case "docs":
      return {
        pr: {
          enabled: true,
          max_changed_files: 100,
          max_lines_changed: 2000,
          require_tests_when_paths_match: [],
          risky_paths: ["mkdocs.yml", "docusaurus.config.*"],
        },
        stewardship: { enabled: true, stale_branch_days: 45, auto_cleanup: false, require_reviewers: 1 },
        security: { enabled: true, require_signed_commits: false, block_force_push_to_default: false },
      };
  }
}

/**
 * Builds a fully-populated, schema-valid MiseConfig for a given
 * profile/environment. Parsing through MiseConfigSchema guarantees the
 * object we go on to render can never drift from what the schema
 * considers valid.
 */
export function buildMiseConfig(profile: RepoProfile, environment: MiseEnvironment): MiseConfig {
  const candidate = {
    version: 1 as const,
    mode: "advisory" as const,
    environment,
    repo_profile: profile,
    policies: defaultPoliciesForProfile(profile),
    modules: {
      pr: true,
      brigade: true,
      salt_shakers: true,
      locker: true,
      gpu: false,
    },
  };
  return MiseConfigSchema.parse(candidate);
}

function yamlStringArray(values: string[], indent: string): string {
  if (values.length === 0) return " []";
  return "\n" + values.map((v) => `${indent}- "${v}"`).join("\n");
}

/** Hand-formats a MiseConfig into the mise.yaml text, comments included. */
export function renderMiseYaml(config: MiseConfig): string {
  const { policies, modules } = config;
  return `# mise.yaml — Mise DevOps Orchestra configuration
# Generated by \`mise-orchestra init\`. Safe to hand-edit; re-running init
# will never overwrite this file without --force.
#
# mode: "advisory" only ever comments on PRs — it cannot block a merge.
# Switching to "enforced" is a deliberate, separate decision your team
# makes once you trust the signal this file produces.

mise:
  version: ${config.version}
  mode: ${config.mode}
  environment: ${config.environment}
  repo_profile: ${config.repo_profile} # best guess — edit freely

  policies:
    pr:
      enabled: ${policies.pr.enabled}
      max_changed_files: ${policies.pr.max_changed_files}
      max_lines_changed: ${policies.pr.max_lines_changed}
      require_tests_when_paths_match:${yamlStringArray(policies.pr.require_tests_when_paths_match, "        ")}
      risky_paths:${yamlStringArray(policies.pr.risky_paths, "        ")}

    stewardship:
      enabled: ${policies.stewardship.enabled}
      stale_branch_days: ${policies.stewardship.stale_branch_days}
      auto_cleanup: ${policies.stewardship.auto_cleanup}
      require_reviewers: ${policies.stewardship.require_reviewers}

    security:
      enabled: ${policies.security.enabled}
      require_signed_commits: ${policies.security.require_signed_commits}
      block_force_push_to_default: ${policies.security.block_force_push_to_default}

  modules:
    pr: ${modules.pr}
    brigade: ${modules.brigade}
    salt_shakers: ${modules.salt_shakers}
    locker: ${modules.locker}
    gpu: ${modules.gpu} # opt-in only — leave false until a policy or event needs it
`;
}
