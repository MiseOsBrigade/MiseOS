#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { loadRegistry, loadManifests, summarizeRegistry, writeJson } from './lib/registry.mjs';

const root = process.cwd();
const outDir = path.join(root, 'apps', 'registry-console', 'src', 'generated');
const manifestsDir = path.join(outDir, 'manifests');
fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(manifestsDir, { recursive: true });

const registry = loadRegistry(root);
const manifests = loadManifests(root);
const summary = summarizeRegistry(root);

writeJson(path.join(outDir, 'index.json'), registry);
writeJson(path.join(outDir, 'analytics.json'), summary);

for (const manifest of manifests) {
  writeJson(path.join(manifestsDir, `${manifest.id}.json`), manifest);
}

const generatedTs = `// Generated by scripts/generate-vite-registry-data.mjs\nexport const generatedAt = ${JSON.stringify(new Date().toISOString())};\nexport const manifestCount = ${manifests.length};\n`;
fs.writeFileSync(path.join(outDir, 'meta.ts'), generatedTs);
console.log(`✓ Vite registry data generated: ${manifests.length} manifests`);
