/** Validates the roster against the schema once, at module init, so a bad
 * entry fails fast in dev/CI instead of silently rendering a broken card. */
export const BRIGADE_ROSTER: readonly BrigadeCard[] = Object.freeze(
  rawRoster.map((card) => BrigadeCardSchema.parse(card)),
);

export const BRIGADES: readonly string[] = Object.freeze(
  Array.from(new Set(BRIGADE_ROSTER.map((c) => c.brigade))).sort(),
);

/** slug -> command string, matching the CLI contract in mise-yaml.ts's
 * neighboring `mise.yaml` config surface: solo, report-emitting, additive. */
export function buildSoloCommand(card: BrigadeCard): string {
  return `mise card run ${card.slug} --mode ${card.mode} --solo --emit report`;
}

