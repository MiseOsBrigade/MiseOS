export function departmentFor(card: MasterRosterCard): Department {
  const dept = DEPARTMENTS.find((d) => d.id === card.departmentId);
  if (!dept) throw new Error(`No department registered for id ${card.departmentId} (card ${card.id})`);
  return dept;
}

export function cardsByDepartment(departmentId: number): MasterRosterCard[] {
  return MASTER_ROSTER.filter((c) => c.departmentId === departmentId).sort((a, b) => a.number - b.number);
}

/** SYNTHESIZED command — see file header. Not sourced from the PDF. */
export function buildMasterRosterCommand(card: MasterRosterCard): string {
  const dept = departmentFor(card);
  const deptSlug = dept.name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
  return `mise roster run ${card.slug} --dept ${deptSlug} --solo --emit report`;
}

